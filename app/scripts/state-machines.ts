/**
 * Regenerates the machine section of docs/state-machines.md from the registries.
 * Run: bun run machines:doc   (add --check to fail when the file is out of date)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { describeMachine, mermaidFor, sharedMachines, type Machine } from "@puck/shared";
import { appMachines } from "../src/machines";

const START = "<!-- machines:start (generated by bun run machines:doc, do not edit by hand) -->";
const END = "<!-- machines:end -->";

// biome-ignore lint/suspicious/noExplicitAny: registries hold machines of different state types.
function section(machine: Machine<any, any>): string {
  const rows = describeMachine(machine);
  const events = [...new Set(machine.samples.events.map((event: { type: string }) => event.type))];
  return [
    `### ${machine.name}`,
    "",
    machine.summary,
    "",
    `Used by: ${machine.usedBy.map((path) => `\`${path}\``).join(", ")}`,
    "",
    `Events: ${events.map((type) => `\`${type}\``).join(", ")}`,
    "",
    "```mermaid",
    mermaidFor(machine),
    "```",
    "",
    rows.length === 0
      ? "No label changes in the samples."
      : ["| From | Event | To |", "| --- | --- | --- |", ...rows.map((row) => `| ${row.from} | ${row.event} | ${row.to} |`)].join("\n"),
    "",
  ].join("\n");
}

const generated = [
  START,
  "",
  "## Shared (packages/shared)",
  "",
  ...sharedMachines.map(section),
  "## App (app/src)",
  "",
  ...appMachines.map(section),
  END,
].join("\n");

const path = new URL("../../docs/state-machines.md", import.meta.url).pathname;
const current = readFileSync(path, "utf8");
const from = current.indexOf(START);
const to = current.indexOf(END);
if (from === -1 || to === -1) throw new Error("docs/state-machines.md is missing the generated markers");
const next = current.slice(0, from) + generated + current.slice(to + END.length);
if (process.argv.includes("--check")) {
  if (next !== current) {
    console.error("docs/state-machines.md is out of date: run bun run machines:doc");
    process.exit(1);
  }
} else {
  writeFileSync(path, next);
}
